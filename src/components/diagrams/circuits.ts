const fmt = (n: number) => +n.toFixed(1);

/** Логарифмическая АЧХ (диаграмма Боде). */
function bodePlot(o: {
	fmin: number;
	fmax: number;
	dbMin: number;
	dbMax: number;
	curves: { fn: (f: number) => number; cls: string }[];
	xlabels: [number, string][];
	ylabels: number[];
	extra?: (X: (f: number) => number, Y: (db: number) => number) => string;
	W?: number;
	H?: number;
}): string {
	const W = o.W ?? 400;
	const H = o.H ?? 230;
	const x0 = 52;
	const x1 = W - 16;
	const y0 = 16;
	const y1 = H - 36;
	const lx = (f: number) => Math.log10(f);
	const X = (f: number) => x0 + ((lx(f) - lx(o.fmin)) / (lx(o.fmax) - lx(o.fmin))) * (x1 - x0);
	const Y = (db: number) => y0 + ((o.dbMax - db) / (o.dbMax - o.dbMin)) * (y1 - y0);
	let s = '';
	for (const [f, lab] of o.xlabels) {
		s += `<path class="ln-thin" d="M${fmt(X(f))} ${y0} V${y1}"/>`;
		s += tx(fmt(X(f)), y1 + 16, lab, 'middle', 't t-s');
	}
	for (const db of o.ylabels) {
		s += `<path class="ln-thin" d="M${x0} ${fmt(Y(db))} H${x1}"/>`;
		s += tx(x0 - 6, fmt(Y(db)) + 4, `${db < 0 ? '−' : ''}${Math.abs(db)}`, 'end', 't t-s');
	}
	s += `<path class="ln" d="M${x0} ${y0} V${y1} H${x1}"/>`;
	s += tx(14, y0 + 4, 'дБ', 'start', 't t-s t-mut');
	for (const c of o.curves) {
		const pts: string[] = [];
		const n = 160;
		for (let i = 0; i <= n; i++) {
			const f = o.fmin * Math.pow(o.fmax / o.fmin, i / n);
			const db = Math.max(o.dbMin, Math.min(o.dbMax, c.fn(f)));
			pts.push(`${fmt(X(f))} ${fmt(Y(db))}`);
		}
		s += `<path class="${c.cls}" d="M${pts.join(' L')}"/>`;
	}
	if (o.extra) s += o.extra(X, Y);
	return s;
}

